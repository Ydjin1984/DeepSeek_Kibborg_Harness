#!/usr/bin/env bash
# launcher.sh - обёртка для ярлыка на рабочем столе.
# Запускает run.sh в отдельном окне терминала и не даёт окну закрыться
# сразу после выхода из меню: результат (сборка, запуск, ошибки) иначе
# исчезает до того, как его успеют прочитать.
#
# В самом run.sh подключение Node не нужно - он делает это сам.

set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# run.sh оставляет курсор в середине строки после отрисовки прогресс-бара.
printf '\n'
cd "$ROOT" || exit 1
bash ./run.sh
code=$?

echo
if [ "$code" -eq 0 ]; then
  echo 'Меню закрыто. Сервер, если он был запущен, продолжает работать в фоне.'
else
  echo "run.sh завершился с кодом $code."
fi
echo "Журналы: $ROOT/.dsh-build"
read -r -p 'Нажмите Enter, чтобы закрыть окно...' _
exit "$code"
